// TTS 正文可朗读化：把「写给人看」的文本改成「读出来才对」的文本。
//
// 本地 TTS 按字面朗读：地址会被念成无意义音节，日期里的短横可能被读成「减」，
// 千分位逗号会打断数字。这里按固定顺序改写，顺序本身是有依赖的：
//   1) 邮箱、电话先换成占位符，避免后面的数字/符号规则把地址拆坏；
//   2) 下划线、英文词内连字符、千分位逗号先还原成词边界；
//   3) 日期、时间、温度、百分比、小数、整数依次转成中文读法；
//   4) 剩余符号逐个换成词，换行并成句号；
//   5) 压缩空白与重复句号，最后还原占位符。
//
// 纯函数：不读配置、不碰网络、不引外部依赖；同一输入永远得到同一输出。

const 数字表 = '零一二三四五六七八九'

/** 逐位读数字（电话、年份、小数部分）；幺=true 时 1 读「幺」，用于电话和纯数字邮箱。 */
function 逐位读(串, 幺 = false) {
  let 出 = ''
  for (const 字 of String(串)) {
    if (字 < '0' || 字 > '9') continue
    出 += 幺 && 字 === '1' ? '幺' : 数字表[Number(字)]
  }
  return 出
}

/** 四位数以内按位读，中间的零合并成一个（1001 → 一千零一）。 */
function 四位转中文(数) {
  const 单位 = ['', '十', '百', '千']
  let 出 = ''
  let 待补零 = false
  for (let i = 0; i < 4; i += 1) {
    const 位 = Math.floor(数 / 10 ** i) % 10
    if (位 === 0) {
      // 只有已经写出更高位时才需要补零，否则前导零会被吃掉。
      if (出) 待补零 = true
    } else {
      if (待补零) {
        出 = '零' + 出
        待补零 = false
      }
      出 = 数字表[位] + 单位[i] + 出
    }
  }
  return 出
}

/** 整数转中文读法：分组（万/亿/万亿）拼接，组内不足四位时补零，开头「一十」读「十」。 */
function 整数转中文(数) {
  if (数 === 0) return '零'
  if (数 < 0) return '负' + 整数转中文(-数)
  // Python 参考实现只到「万亿」；再多一位会越界。这里补一个更大的单位兜底，
  // 正常聊天文本到不了这一档，但也不该因此抛错。
  const 大单位 = ['', '万', '亿', '万亿', '兆']
  const 组们 = []
  let 余 = 数
  while (余 > 0) {
    组们.push(余 % 10000)
    余 = Math.floor(余 / 10000)
  }
  let 结果 = ''
  for (let i = 组们.length - 1; i >= 0; i -= 1) {
    const 组 = 组们[i]
    if (组 === 0) {
      if (结果 && !结果.endsWith('零')) 结果 += '零'
      continue
    }
    // 高位组存在、而本组不足四位（如 10001 的 0001）时补一个零。
    if (结果 && 组 < 1000 && !结果.endsWith('零')) 结果 += '零'
    结果 += 四位转中文(组) + (大单位[i] ?? '')
  }
  结果 = 结果.replace(/零+$/, '')
  if (结果.startsWith('一十')) 结果 = 结果.slice(1)
  return 结果
}

/** 数字串转中文：先去掉千分位逗号；小数按「整数部分 + 点 + 逐位读小数」。 */
function 数字转中文(串) {
  const 纯 = String(串).replace(/,/g, '')
  const 点 = 纯.indexOf('.')
  if (点 >= 0) {
    return 整数转中文(Number(纯.slice(0, 点))) + '点' + 逐位读(纯.slice(点 + 1))
  }
  return 整数转中文(Number(纯))
}

/** 邮箱按字母/数字拼读：@ 读 at，域名里的点读 dot；纯数字本地部分用「幺」。 */
function 拼读邮箱(地址) {
  const 分界 = 地址.lastIndexOf('@')
  const 本地 = 地址.slice(0, 分界)
  const 域名 = 地址.slice(分界 + 1)
  const 纯数字 = /^[0-9]+$/.test(本地)
  const 拼 = (片段, 用幺) => {
    let 文 = 片段
      .replace(/\./g, ' dot ')
      .replace(/_/g, ' underscore ')
      .replace(/\+/g, ' plus ')
      .replace(/-/g, ' dash ')
    文 = 文.replace(/[0-9]+/g, (数字) => 逐位读(数字, 用幺))
    return 文.replace(/\s+/g, ' ').trim()
  }
  return 拼(本地, 纯数字) + ' at ' + 拼(域名, false)
}

/** 电话逐位读：分段之间用逗号停顿，+86 读「加八六」。 */
function 拼读电话(号) {
  const 段们 = String(号).trim().split(/[-\s]+/)
  const 出 = []
  for (const 段 of 段们) {
    if (!段) continue
    if (段.startsWith('+')) {
      const 体 = 段.slice(1)
      出.push(体 ? '加' + 逐位读(体, true) : '加')
    } else {
      出.push(逐位读(段, true))
    }
  }
  return 出.join('，')
}

/** 分钟/秒固定两位：不足十补「零」（05 → 零五），避免读成「零零五」。 */
function 读两位(两位) {
  const 值 = Number(两位)
  return 值 < 10 ? '零' + 数字表[值] : 整数转中文(值)
}

/** 占位符编号：A、B…Z、AA…；只用字母，避免被数字/符号规则二次命中。 */
function 编号字母(序号) {
  let 出 = ''
  let 余 = 序号 + 1
  while (余 > 0) {
    余 -= 1
    出 = String.fromCharCode(65 + (余 % 26)) + 出
    余 = Math.floor(余 / 26)
  }
  return 出
}

const 邮箱式 = /(?<![A-Za-z0-9._%+\-])[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}(?![A-Za-z0-9\-])/g

const 电话式们 = [
  /(?<!\d)(?:\+\s?86[-\s]?)?1[3-9]\d(?:[-\s]?\d{4}){2}(?!\d)/g,
  /(?<!\d)[48]00[-\s]?\d{3}[-\s]?\d{4}(?!\d)/g,
  /(?<!\d)0\d{2,3}[-\s]\d{7,8}(?!\d)/g,
  /(?<!\d)\+\d{1,3}[-\s]\d{4,14}(?!\d)/g,
  /(?<!\d)\+\d{7,15}(?!\d)/g,
]

// 符号按「读出来的词」替换；@ & | 前后补空格，避免和相邻英文粘成一个词。
const 符号表 = {
  '+': '加', '-': '减', '*': '乘', '×': '乘',
  '/': '除以', '÷': '除以', '=': '等于',
  '@': 'at', '#': '井号', '&': 'and', '|': 'or',
  '^': '次方', '~': '波浪号', '<': '小于', '>': '大于',
  '$': '美元', '€': '欧元', '£': '英镑', '¥': '元',
  '±': '正负', '≈': '约等于', '≠': '不等于',
  '≤': '小于等于', '≥': '大于等于',
  '℃': '摄氏度', '°': '度',
  '(': '括号', ')': '括号',
  '[': '方括号', ']': '方括号',
  '{': '花括号', '}': '花括号',
}
const 英文符号 = new Set(['@', '&', '|'])

/**
 * 把一段文本转成适合交给 TTS 朗读的写法。
 * @param {string} text 原始文本（允许空串、null）
 * @returns {string} 可朗读文本；全空白输入返回空串
 */
export function tts友好化(text) {
  let 文 = String(text ?? '').replace(/\r\n/g, '\n').replace(/\r/g, '\n')

  // 占位符：地址先整体藏起来，等所有数字/符号规则跑完再放回。
  const 占位 = []
  const 存 = (替换) => {
    const 键 = '\u0000' + 编号字母(占位.length) + '\u0000'
    占位.push([键, 替换])
    return 键
  }

  // 1. 邮箱、电话
  文 = 文.replace(邮箱式, (匹配) => 存(拼读邮箱(匹配)))
  for (const 式 of 电话式们) {
    文 = 文.replace(式, (匹配) => 存(拼读电话(匹配)))
  }

  // 2. 词边界：下划线、英文词内连字符、千分位逗号
  文 = 文.replace(/_/g, ' ')
  文 = 文.replace(/(?<=[A-Za-z])-(?=[A-Za-z])/g, ' ')
  文 = 文.replace(/(?<=\d),(?=\d{3}(?!\d))/g, '')

  // 3. 日期：先带分隔符的完整日期，再「年月日」，最后只剩年、年月
  文 = 文.replace(/(?<!\d)(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})(?!\d)/g, (_, 年, 月, 日) =>
    逐位读(年) + '年' + 整数转中文(Number(月)) + '月' + 整数转中文(Number(日)) + '日')
  文 = 文.replace(/(?<!\d)(\d{4})年(\d{1,2})月(\d{1,2})[日号]?/g, (_, 年, 月, 日) =>
    逐位读(年) + '年' + 整数转中文(Number(月)) + '月' + 整数转中文(Number(日)) + '日')
  文 = 文.replace(/(?<!\d)(\d{4})年(\d{1,2})月/g, (_, 年, 月) =>
    逐位读(年) + '年' + 整数转中文(Number(月)) + '月')
  文 = 文.replace(/(?<!\d)(\d{4})年/g, (_, 年) => 逐位读(年) + '年')

  // 4. 时间：9:07 → 九点零七分；带秒时再接「零九秒」
  文 = 文.replace(/(?<!\d)(\d{1,2}):(\d{2})(?::(\d{2}))?(?!\d)/g, (_, 时, 分, 秒) => {
    const 结果 = 整数转中文(Number(时)) + '点' + 读两位(分) + '分'
    return 秒 === undefined ? 结果 : 结果 + 读两位(秒) + '秒'
  })

  // 5. 温度 / 角度
  文 = 文.replace(/(?<![\d.])(\d+(?:\.\d+)?)\s*℃/g, (_, 数) => 数字转中文(数) + '摄氏度')
  文 = 文.replace(/(?<![\d.])(\d+(?:\.\d+)?)\s*°C/g, (_, 数) => 数字转中文(数) + '摄氏度')
  文 = 文.replace(/(?<![\d.])(\d+(?:\.\d+)?)\s*°/g, (_, 数) => 数字转中文(数) + '度')

  // 6. 百分比
  文 = 文.replace(/(?<![\d.])(\d+(?:\.\d+)?)\s*%/g, (_, 数) => '百分之' + 数字转中文(数))

  // 7. 小数、剩余整数
  文 = 文.replace(/(?<![\d.])(\d+\.\d+)(?![\d.])/g, (_, 数) => 数字转中文(数))
  文 = 文.replace(/(?<![\d.])(\d+)(?![\d.])/g, (_, 数) => 整数转中文(Number(数)))

  // 8. 剩余符号
  for (const 符 of Object.keys(符号表)) {
    if (英文符号.has(符)) 文 = 文.replaceAll(符, ' ' + 符号表[符] + ' ')
    else 文 = 文.replaceAll(符, 符号表[符])
  }

  // 9. 换行并句、压缩空白与重复句号
  文 = 文.replace(/\n+/g, '。')
  文 = 文.replace(/[ \t\u3000]+/g, ' ')
  文 = 文.replace(/。+/g, '。')
  文 = 文.replace(/\s*。\s*/g, '。')
  文 = 文.replace(/^。+/, '').trim()

  // 10. 还原占位符
  for (const [键, 替换] of 占位) 文 = 文.split(键).join(替换)
  return 文
}

/** 单段语音的默认字数上限：远低于服务端 5000 字上限，长文本听起来才不噎。 */
export const 语音单段上限 = 200

/**
 * 把长文本按句子切成若干段，每段不超过上限。
 *
 * 切分优先级：句末标点 > 逗号/顿号/冒号 > 硬切。这样合成出来是几句完整的话，
 * 不会在半句话中间断气；接口一次只合成一段，调用方按返回顺序发送即可。
 *
 * @param {string} text 已可朗读化的文本
 * @param {number} 上限 单段最大字数
 * @returns {string[]} 非空段落；空文本返回空数组
 */
export function 切分语音文本(text, 上限 = 语音单段上限) {
  const 全文 = String(text ?? '')
  if (!全文) return []
  const 限制 = Math.max(1, Math.floor(Number(上限)) || 语音单段上限)
  if (全文.length <= 限制) return [全文]

  const 句们 = 全文.match(/[^。！？!?；;…]+[。！？!?；;…]*|[。！？!?；;…]+/g) || [全文]
  const 段们 = []
  let 当前 = ''

  const 收尾 = () => {
    const 净 = 当前.trim()
    if (净) 段们.push(净)
    当前 = ''
  }

  for (const 句 of 句们) {
    if (句.length > 限制) {
      // 单句就超限：先按逗号类停顿切，仍超限才硬切。
      收尾()
      const 小句们 = 句.match(/[^，,、：:]+[，,、：:]*|[，,、：:]+/g) || [句]
      for (const 小句 of 小句们) {
        if (小句.length > 限制) {
          收尾()
          for (let i = 0; i < 小句.length; i += 限制) 段们.push(小句.slice(i, i + 限制))
        } else if (当前.length + 小句.length > 限制) {
          收尾()
          当前 = 小句
        } else {
          当前 += 小句
        }
      }
      continue
    }
    if (当前.length + 句.length > 限制) 收尾()
    当前 += 句
  }
  收尾()
  return 段们
}
